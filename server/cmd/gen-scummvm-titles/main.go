// gen-scummvm-titles regenerates server/internal/igdb/scummvm_titles_data.go
// from the canonical ScummVM games list at
// scummvm/scummvm-web/data/en/games.yaml.
//
// The yaml entries are keyed by `<engine_id>:<gameid>`. We strip the
// engine prefix and emit a Go map[gameid]title. About 1,138 games today
// covering every game ScummVM officially supports.
//
// Collisions: very rare (only `driller` today — Freescape 1987 vs.
// Wintermute 2010). Resolved by preferring the older title (which is
// almost always the more famous one users actually drop in their
// libraries).
//
// Run:
//
//	cd server && go run ./cmd/gen-scummvm-titles
//
// Reads from the URL by default; override with -input <path> for offline
// regeneration.
package main

import (
	"flag"
	"fmt"
	"io"
	"maps"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	defaultURL = "https://raw.githubusercontent.com/scummvm/scummvm-web/master/data/en/games.yaml"
	outPath    = "internal/igdb/scummvm_titles_data.go"
)

type gameEntry struct {
	ID       string `yaml:"id"`
	Name     string `yaml:"name"`
	EngineID string `yaml:"engine_id"`
	Year     string `yaml:"year"`
}

func main() {
	input := flag.String("input", "", "Optional local path to games.yaml; defaults to fetching from GitHub.")
	flag.Parse()

	var src io.Reader
	if *input != "" {
		f, err := os.Open(*input)
		if err != nil {
			fatal("open input: %v", err)
		}
		defer f.Close()
		src = f
	} else {
		resp, err := http.Get(defaultURL)
		if err != nil {
			fatal("fetch %s: %v", defaultURL, err)
		}
		defer resp.Body.Close()
		if resp.StatusCode != 200 {
			fatal("fetch %s: HTTP %d", defaultURL, resp.StatusCode)
		}
		src = resp.Body
	}

	var entries []gameEntry
	dec := yaml.NewDecoder(src)
	if err := dec.Decode(&entries); err != nil {
		fatal("parse yaml: %v", err)
	}
	if len(entries) == 0 {
		fatal("no entries parsed")
	}

	// Build map gameid -> chosen entry. On collision, keep the older
	// year (that's almost always the more famous game; the modern
	// re-uses tend to be obscure indie titles).
	chosen := make(map[string]gameEntry)
	collisions := make(map[string][]gameEntry)
	for _, e := range entries {
		gameid := strings.TrimSpace(extractGameID(e.ID))
		name := strings.TrimSpace(e.Name)
		if gameid == "" || name == "" {
			continue
		}
		if existing, ok := chosen[gameid]; ok {
			collisions[gameid] = append(collisions[gameid], existing, e)
			if older(e, existing) {
				chosen[gameid] = e
			}
			continue
		}
		chosen[gameid] = e
	}

	// Backfill `<base>1` aliases. ScummVM upstream lists the first game
	// of a series under the bare id (`monkey`) and sequels with explicit
	// numbering (`monkey2`, `monkey4`). User directory layouts often use
	// `<base>1` for the first game, paralleling the sequels — but the
	// upstream YAML doesn't carry that alias. Add it: for every `<base>`
	// where `<base>2`/`<base>3`/`<base>4`/`<base>5` exists but
	// `<base>1` doesn't, set `chosen[<base>1] = chosen[<base>]`.
	//
	// Skip when `<base>` itself ends in a digit (e.g. `sq4`, `sword2`) —
	// the resulting compound (`sq41`, `sword21`) is noise that no user
	// would type, and the digit-suffixed siblings the heuristic latched
	// onto (`sq45`, `sword25`) are sub-version markers, not sequels.
	for base, entry := range maps.Clone(chosen) {
		if base == "" {
			continue
		}
		if last := base[len(base)-1]; last >= '0' && last <= '9' {
			continue
		}
		if _, has := chosen[base+"1"]; has {
			continue
		}
		hasSequel := false
		for _, suffix := range []string{"2", "3", "4", "5"} {
			if _, ok := chosen[base+suffix]; ok {
				hasSequel = true
				break
			}
		}
		if !hasSequel {
			continue
		}
		chosen[base+"1"] = entry
	}

	// Sort gameids for deterministic output.
	ids := make([]string, 0, len(chosen))
	for id := range chosen {
		ids = append(ids, id)
	}
	sort.Strings(ids)

	repoRoot, err := os.Getwd()
	if err != nil {
		fatal("cwd: %v", err)
	}
	out := filepath.Join(repoRoot, outPath)

	var buf strings.Builder
	buf.WriteString("// Code generated by `go run ./cmd/gen-scummvm-titles`. DO NOT EDIT.\n")
	buf.WriteString("//\n")
	buf.WriteString("// Source: https://github.com/scummvm/scummvm-web/blob/master/data/en/games.yaml\n")
	buf.WriteString("//\n")
	buf.WriteString("// To regenerate, from the server/ directory:\n")
	buf.WriteString("//   go run ./cmd/gen-scummvm-titles\n")
	buf.WriteString("\n")
	buf.WriteString("package igdb\n")
	buf.WriteString("\n")
	buf.WriteString(fmt.Sprintf("// scummvmGameTitles maps every ScummVM gameid to its canonical title.\n"))
	buf.WriteString(fmt.Sprintf("// %d entries covering every game ScummVM officially supports.\n", len(ids)))
	buf.WriteString("var scummvmGameTitles = map[string]string{\n")
	for _, id := range ids {
		title := chosen[id].Name
		buf.WriteString(fmt.Sprintf("\t%q: %q,\n", id, title))
	}
	buf.WriteString("}\n")

	if err := os.WriteFile(out, []byte(buf.String()), 0644); err != nil {
		fatal("write %s: %v", out, err)
	}

	fmt.Printf("wrote %s — %d gameids\n", out, len(ids))
	if len(collisions) > 0 {
		fmt.Printf("note: %d gameid collision(s) resolved in favour of the older title:\n", len(collisions))
		for gid, list := range collisions {
			fmt.Printf("  %s: kept %q (%s), dropped %q (%s)\n",
				gid,
				chosen[gid].Name, chosen[gid].Year,
				otherTitle(list, chosen[gid].Name), otherYear(list, chosen[gid].Name))
		}
	}
}

// extractGameID parses `<engine>:<gameid>` and returns the gameid part.
// Returns the input unchanged when there's no colon.
func extractGameID(idField string) string {
	if i := strings.Index(idField, ":"); i >= 0 {
		return idField[i+1:]
	}
	return idField
}

// older reports whether [a] was released before [b]. When either year is
// missing or unparseable, returns false (keep the existing chosen entry).
func older(a, b gameEntry) bool {
	if a.Year == "" || b.Year == "" {
		return false
	}
	return a.Year < b.Year
}

func otherTitle(list []gameEntry, kept string) string {
	for _, e := range list {
		if e.Name != kept {
			return e.Name
		}
	}
	return ""
}

func otherYear(list []gameEntry, kept string) string {
	for _, e := range list {
		if e.Name != kept {
			return e.Year
		}
	}
	return ""
}

func fatal(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, "gen-scummvm-titles: "+format+"\n", args...)
	os.Exit(1)
}
